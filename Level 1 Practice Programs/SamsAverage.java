// Program 2: Calculate Sam's Average Mark
public class SamsAverage {
    public static void main(String[] args) {
        // Define marks
        int maths = 94;
        int physics = 95;
        int chemistry = 96;

        // Calculate average
        double average = (maths + physics + chemistry) / 3.0;

        // Print the result
        System.out.println("Sam’s average mark in PCM is " + average);
    }
}